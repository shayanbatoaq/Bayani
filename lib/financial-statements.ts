export type ScheduleKey = (typeof scheduleLines)[number]["key"]
export type FinancialLedger = {
  id: string
  ledgerName: string
  amount: number
  scheduleKey: string
}
export type OpeningEquity = {
  capital: number
  earnings: number
  retained: number
  shareholder: number
}
export type FinancialInput = {
  clientId: string
  clientName: string
  year: number
  currency: string
  rows: FinancialLedger[]
  openingEquity: OpeningEquity | null
}
export type ReportLine = {
  label: string
  note?: number
  amount: number | null
  kind?: "heading" | "total"
  source?: string
  row: number
}
export type EquityLine = {
  label: string
  values: (number | null)[]
  kind?: "total"
}
export type FinancialOutput = {
  schedules: ReportLine[]
  bs: ReportLine[]
  income: ReportLine[]
  equity: EquityLine[]
  warnings: string[]
  unmapped: string[]
  trialBalanceTotal: number
  balanceDifference: number
  closingEquity: OpeningEquity
  netProfit: number
}
export type FinancialRecord = FinancialInput & {
  id: string
  revision: number
  updatedAt: string
  statements: FinancialOutput
}

export function suggestSchedule(
  name: string,
  amount: number
): ScheduleKey | "" {
  const rules: [RegExp, ScheduleKey][] = [
    [/prepaid|prepayment/i, "prepayments"],
    [/allowance for bad|trade receivable|accounts receivable/i, "receivables"],
    [
      /allowance for depreciation|accumulated depreciation|fixed asset|property.*equipment/i,
      "ppe",
    ],
    [/financial asset|investment/i, "financialAssets"],
    [/inventor/i, "inventory"],
    [/due from.*related/i, "relatedReceivable"],
    [/due to.*related/i, "relatedPayable"],
    [/director.*loan|loan.*director/i, "directorLoan"],
    [/long.term.*liabilit|long.term.*loan/i, "longTermLiabilities"],
    [/share.*capital/i, "capital"],
    [/retained earning/i, "retained"],
    [/dividend|drawing/i, "dividends"],
    [/current account|shareholder/i, "shareholder"],
    [/end of service|gratuity/i, "endOfService"],
    [/accounts payable|trade payable/i, "payables"],
    [/accru|provision|salar.*payable|wages.*payable/i, "accruals"],
    [/advance.*supplier/i, "supplierAdvances"],
    [/advance.*customer/i, "customerAdvances"],
    [/deposit/i, "deposits"],
    [/cost of (goods sold|sales)/i, "costOfSales"],
    [/other income/i, "otherIncome"],
    [/revenue|^sales$/i, "sales"],
    [/bank charges|interest|finance cost/i, "finance"],
    [/exchange|revaluation/i, "exchange"],
    [/consultancy/i, "consultancy"],
    [/legal|professional/i, "legal"],
    [/market|advertis/i, "marketing"],
    [/meal|entertainment/i, "entertainment"],
    [/medical/i, "medical"],
    [/rent|warehouse/i, "rent"],
    [/payroll|salar|wages/i, "payroll"],
    [/subscription/i, "subscriptions"],
    [/travel/i, "travel"],
    [/utilit/i, "utilities"],
    [/vehicle/i, "vehicle"],
    [/office|printing|stationery|postage/i, "office"],
    [/expense|insurance|commission|discount given/i, "otherExpenses"],
    [/cash/i, "cash"],
    [/bank/i, "bank"],
  ]
  if (/\b(vat|tax)\b/i.test(name))
    return amount >= 0 ? "taxReceivable" : "taxPayable"
  return rules.find(([pattern]) => pattern.test(name))?.[1] ?? ""
}

export function calculateFinancials(input: FinancialInput): FinancialOutput {
  const values = Object.fromEntries(
    scheduleLines.map((line) => [line.key, 0])
  ) as Record<ScheduleKey, number>
  const unmapped: string[] = []
  for (const ledger of input.rows) {
    const line = scheduleLines.find((line) => line.key === ledger.scheduleKey)
    if (!line) {
      unmapped.push(ledger.ledgerName)
      continue
    }
    values[line.key] += Math.round(ledger.amount * 100) * line.sign
  }
  const v = (key: ScheduleKey) => values[key] / 100
  const sum = (...keys: ScheduleKey[]) =>
    keys.reduce((n, key) => n + values[key], 0) / 100
  const round = (n: number) => Math.round(n * 100) / 100
  const schedules: ReportLine[] = scheduleLines.map((line) => ({
    label: line.label,
    note: line.note,
    amount: v(line.key),
    row: line.row,
  }))
  schedules.push(
    {
      row: 59,
      label: "Employee end of services - opening balance",
      amount: null,
    },
    { row: 60, label: "Provision for the year - not supplied", amount: null },
    { row: 61, label: "Payments during the year - not supplied", amount: null },
    {
      row: 65,
      label: "Shareholder's current account - beginning balance",
      amount: input.openingEquity?.shareholder ?? null,
    },
    {
      row: 66,
      label: "Net movement during the year",
      amount: input.openingEquity
        ? round(v("shareholder") - input.openingEquity.shareholder)
        : null,
      source: "S:67-S:65",
    }
  )
  const totals: [number, string, ScheduleKey[]][] = [
    [9, "Financial assets", ["financialAssets"]],
    [13, "Inventories", ["inventory"]],
    [17, "Trade receivables", ["receivables"]],
    [
      25,
      "Advances, Deposits & Prepayments",
      [
        "deposits",
        "supplierAdvances",
        "prepayments",
        "taxReceivable",
        "otherReceivables",
      ],
    ],
    [30, "Due from related party", ["relatedReceivable"]],
    [35, "Cash & Cash Equivalent", ["cash", "bank"]],
    [40, "Non-current liabilities", ["longTermLiabilities", "directorLoan"]],
    [44, "Trade payables", ["payables"]],
    [
      51,
      "Accruals, Provisions & Other Payables",
      ["accruals", "customerAdvances", "taxPayable", "otherPayables"],
    ],
    [56, "Due to related party", ["relatedPayable"]],
    [71, "Sales", ["sales"]],
    [75, "Cost of sales", ["costOfSales"]],
    [
      91,
      "Administration expenses",
      scheduleLines.filter((line) => line.note === 18).map((line) => line.key),
    ],
    [96, "Bank charges and interest", ["finance", "exchange"]],
  ]
  for (const [row, label, keys] of totals)
    schedules.push({
      row,
      label: `Total ${label}`,
      amount: sum(...keys),
      kind: "total",
      source: keys
        .map(
          (key) => `S:${scheduleLines.find((line) => line.key === key)!.row}`
        )
        .join("+"),
    })
  const sub = (row: number) =>
    schedules.find((line) => line.row === row)!.amount!
  const profit = round(
    v("sales") - v("costOfSales") + v("otherIncome") - sub(91) - sub(96)
  )
  const income: ReportLine[] = [
    { row: 10, label: "SALES", note: 16, amount: v("sales"), source: "S:71" },
    {
      row: 11,
      label: "Cost of sales",
      note: 17,
      amount: -v("costOfSales"),
      source: "-S:75",
    },
    {
      row: 12,
      label: "GROSS PROFIT",
      amount: round(v("sales") - v("costOfSales")),
      kind: "total",
      source: "I:10+I:11",
    },
    {
      row: 13,
      label: "Other income",
      note: 21,
      amount: v("otherIncome"),
      source: "S:110",
    },
    {
      row: 14,
      label: "Administrative and general expenses",
      note: 18,
      amount: -sub(91),
      source: "-S:91",
    },
    {
      row: 15,
      label: "Bank charges and interest",
      note: 19,
      amount: -sub(96),
      source: "-S:96",
    },
    {
      row: 16,
      label: "NET PROFIT / (LOSS) FOR THE YEAR",
      amount: profit,
      kind: "total",
      source: "I:12+I:13+I:14+I:15",
    },
  ]
  const closingEquity = {
    capital: v("capital"),
    retained: round(v("retained") - v("dividends")),
    earnings: profit,
    shareholder: v("shareholder"),
  }
  const equityTotal = round(
    Object.values(closingEquity).reduce((sum, value) => sum + value, 0)
  )
  const nonCurrentAssets = sum("ppe", "financialAssets")
  const currentAssets = round(
    v("inventory") + v("receivables") + sub(25) + sub(30) + sub(35)
  )
  const currentLiabilities = round(
    sub(44) + sub(51) + sub(56) + v("endOfService")
  )
  const assets = round(nonCurrentAssets + currentAssets)
  const equityLiabilities = round(equityTotal + sub(40) + currentLiabilities)
  const bs: ReportLine[] = [
    { row: 8, label: "ASSETS", kind: "heading", amount: null },
    { row: 10, label: "NON CURRENT ASSETS", kind: "heading", amount: null },
    {
      row: 11,
      label: "Property, plant and equipment",
      note: 3,
      amount: v("ppe"),
      source: "S:100",
    },
    {
      row: 12,
      label: "Financial assets",
      note: 4,
      amount: v("financialAssets"),
      source: "S:9",
    },
    {
      row: 13,
      label: "TOTAL NON CURRENT ASSETS",
      amount: nonCurrentAssets,
      kind: "total",
      source: "B:11+B:12",
    },
    { row: 16, label: "CURRENT ASSETS", amount: null, kind: "heading" },
    {
      row: 17,
      label: "Inventories",
      note: 5,
      amount: v("inventory"),
      source: "S:13",
    },
    {
      row: 18,
      label: "Trade receivables",
      note: 6,
      amount: v("receivables"),
      source: "S:17",
    },
    {
      row: 19,
      label: "Advances, Deposits & Prepayments",
      note: 7,
      amount: sub(25),
      source: "S:25",
    },
    {
      row: 20,
      label: "Due from related party",
      note: 8,
      amount: sub(30),
      source: "S:30",
    },
    {
      row: 21,
      label: "Cash & Cash Equivalent",
      note: 9,
      amount: sub(35),
      source: "S:35",
    },
    {
      row: 22,
      label: "TOTAL CURRENT ASSETS",
      amount: currentAssets,
      kind: "total",
      source: "B:17+B:18+B:19+B:20+B:21",
    },
    {
      row: 25,
      label: "TOTAL ASSETS",
      amount: assets,
      kind: "total",
      source: "B:13+B:22",
    },
    { row: 27, label: "LIABILITIES AND EQUITY", amount: null, kind: "heading" },
    {
      row: 31,
      label: "NON CURRENT LIABILITIES",
      amount: null,
      kind: "heading",
    },
    {
      row: 32,
      label: "Loan from director",
      amount: v("directorLoan"),
      source: "S:39",
    },
    {
      row: 33,
      label: "Other non-current liabilities",
      amount: v("longTermLiabilities"),
      source: "S:38",
    },
    {
      row: 34,
      label: "TOTAL NON CURRENT LIABILITIES",
      note: 10,
      amount: sub(40),
      source: "B:32+B:33",
      kind: "total",
    },
    { row: 37, label: "CURRENT LIABILITIES", amount: null, kind: "heading" },
    {
      row: 38,
      label: "Trade payables",
      note: 11,
      amount: sub(44),
      source: "S:44",
    },
    {
      row: 39,
      label: "Accruals, Provisions & Other Payables",
      note: 12,
      amount: sub(51),
      source: "S:51",
    },
    {
      row: 40,
      label: "Due to related party",
      note: 13,
      amount: sub(56),
      source: "S:56",
    },
    {
      row: 41,
      label: "Employee end of services",
      note: 14,
      amount: v("endOfService"),
      source: "S:62",
    },
    {
      row: 42,
      label: "TOTAL CURRENT LIABILITIES",
      amount: currentLiabilities,
      source: "B:38+B:39+B:40+B:41",
      kind: "total",
    },
    { row: 45, label: "EQUITY FUNDS", amount: null, kind: "heading" },
    {
      row: 46,
      label: "Share capital",
      amount: closingEquity.capital,
      source: "S:104",
    },
    { row: 47, label: "Current year earnings", amount: profit, source: "I:16" },
    {
      row: 48,
      label: "Retained earnings",
      amount: closingEquity.retained,
      source: "S:105-S:106",
    },
    {
      row: 49,
      label: "Shareholders current account",
      amount: closingEquity.shareholder,
      source: "S:67",
    },
    {
      row: 50,
      label: "TOTAL EQUITY",
      amount: equityTotal,
      source: "B:46+B:47+B:48+B:49",
      kind: "total",
    },
    {
      row: 52,
      label: "TOTAL EQUITY AND LIABILITIES",
      amount: equityLiabilities,
      source: "B:34+B:42+B:50",
      kind: "total",
    },
  ]
  const opening = input.openingEquity
  const close = [
    closingEquity.capital,
    profit,
    closingEquity.retained,
    closingEquity.shareholder,
    equityTotal,
  ]
  const addTotal = (values: number[]) => [
    ...values,
    round(values.reduce((n, v) => n + v, 0)),
  ]
  const equity: EquityLine[] = [
    {
      label: "Opening balances",
      values: opening
        ? addTotal([
            opening.capital,
            opening.earnings,
            opening.retained,
            opening.shareholder,
          ])
        : Array(5).fill(null),
    },
    {
      label: `Profit / (loss) for ${input.year}`,
      values: [0, profit, 0, 0, profit],
    },
    {
      label: "Transfer of prior-year earnings",
      values: opening
        ? [0, -opening.earnings, opening.earnings, 0, 0]
        : Array(5).fill(null),
    },
    {
      label: "Dividends / drawings",
      values: [0, 0, -v("dividends"), 0, -v("dividends")],
    },
    {
      label: "Other net movements",
      values: opening
        ? addTotal([
            round(closingEquity.capital - opening.capital),
            0,
            round(v("retained") - opening.retained - opening.earnings),
            round(closingEquity.shareholder - opening.shareholder),
          ])
        : Array(5).fill(null),
    },
    { label: `Closing balances ${input.year}`, values: close, kind: "total" },
  ]
  const trialBalanceTotal =
    input.rows.reduce((total, row) => total + Math.round(row.amount * 100), 0) /
    100
  const difference = round(assets - equityLiabilities)
  const warnings: string[] = []
  if (unmapped.length)
    warnings.push(`${unmapped.length} ledgers need a schedule allocation.`)
  if (Math.abs(trialBalanceTotal) >= 0.01)
    warnings.push(
      `Trial balance difference: ${trialBalanceTotal.toFixed(2)} ${input.currency}.`
    )
  if (Math.abs(difference) >= 0.01)
    warnings.push(
      `Balance sheet difference: ${difference.toFixed(2)} ${input.currency}.`
    )
  if (!opening)
    warnings.push(
      "Opening equity is missing; equity movements are unavailable."
    )
  return {
    schedules: schedules.sort((a, b) => a.row - b.row),
    bs,
    income,
    equity,
    warnings,
    unmapped,
    trialBalanceTotal,
    balanceDifference: difference,
    closingEquity,
    netProfit: profit,
  }
}
